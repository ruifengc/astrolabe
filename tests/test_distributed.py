"""Cross-system trace propagation: shared trace_id, composite PK, export.

A trace may span multiple systems. Each system records only its own spans
(own db file); the first hop generates the global trace_id, downstream hosts
receive it (via get_trace_context) and pass it into their own entry point.
traces.global_trace_id is therefore decoupled from the local root span id, and the
traces table keys on (trace_id, host) so systems never overwrite each other.
"""

from __future__ import annotations

import asyncio

from astrolabe import Astrolabe, aspan, get_trace_context, span
from astrolabe.backends.sqlite import SQLiteBackend


def test_first_hop_generates_trace_id(tmp_path):
    a = Astrolabe(str(tmp_path / "t.db"))
    try:
        with a.trace("ask", host="system-a", question="q") as c:
            # trace_id is generated by the first hop and decoupled from the
            # local root span id
            assert c.global_trace_id
            assert len(c.global_trace_id) == 16
            assert c.root_span_id
            assert c.global_trace_id != c.root_span_id
            c.set_root_attrs(answer="final answer", hop_count=3)

        t = a.list_traces()[0]
        assert t["trace_id"] == c.global_trace_id
        assert t["metadata"]["answer"] == "final answer"
        assert t["metadata"]["hop_count"] == 3
        spans = a.get_trace_spans(c.global_trace_id)
        root = next(s for s in spans if s["parent_span_id"] is None)
        assert root["span_id"] == c.root_span_id          # local root span id
        assert root["metadata"]["answer"] == "final answer"
        assert all(s["trace_id"] == c.global_trace_id for s in spans)
    finally:
        a.close()


def test_downstream_accepts_upstream_trace_id(tmp_path):
    a = Astrolabe(str(tmp_path / "t.db"))
    try:
        with a.trace("ask", host="system-b",
                     trace_id="deadbeef12345678", question="q") as c:
            assert c.global_trace_id == "deadbeef12345678"
            assert c.global_trace_id != c.root_span_id

        t = a.list_traces()[0]
        assert t["trace_id"] == "deadbeef12345678"
        assert t["host"] == "system-b"
        spans = a.get_trace_spans("deadbeef12345678")
        assert all(s["trace_id"] == "deadbeef12345678" for s in spans)
    finally:
        a.close()


def test_same_trace_id_two_hosts_coexist(tmp_path):
    """Composite PK (trace_id, host): two systems writing the same global
    trace id into one db do not overwrite each other."""
    a = Astrolabe(str(tmp_path / "t.db"))
    try:
        with a.trace("ask", host="alpha", trace_id="shared12345678"):
            pass
        with a.trace("ask", host="beta", trace_id="shared12345678"):
            pass

        assert a.count_traces() == 2
        rows = a.list_traces()
        assert {r["host"] for r in rows} == {"alpha", "beta"}
        assert all(r["trace_id"] == "shared12345678" for r in rows)
    finally:
        a.close()


def test_batch_idempotent_per_host(tmp_path):
    """Re-flushing the same (trace_id, host) replaces, never duplicates."""
    b = SQLiteBackend(str(tmp_path / "t.db"))
    try:
        for _ in range(2):
            b.write_batch([dict(
                trace_id="shared12345678", host="alpha", root_span_id="root123",
                status="done",
                duration_ms=10, error="", metadata={"hop_count": 1},
                created_at="2026-01-01T00:00:00+00:00",
                updated_at="2026-01-01T00:00:00+00:00",
            )], [])
        assert b.count_traces() == 1
        assert b.get_trace("shared12345678")["metadata"]["hop_count"] == 1
        assert b.get_trace("shared12345678")["root_span_id"] == "root123"
    finally:
        b.close()


def test_get_trace_context_inside_trace(tmp_path):
    a = Astrolabe(str(tmp_path / "t.db"))
    try:
        captured = {}

        def downstream_call():
            # boundary code reads the propagation context and forwards it
            captured.update(get_trace_context() or {})

        with a.trace("ask", host="system-a") as c:
            with span("hop"):
                downstream_call()

        assert captured == {"trace_id": c.global_trace_id, "host": "system-a"}
    finally:
        a.close()


def test_get_trace_context_async(tmp_path):
    a = Astrolabe(str(tmp_path / "t.db"))

    async def scenario():
        async with a.atrace("ask", host="sys-a") as c:
            async with aspan("hop"):
                ctx = get_trace_context()
            return c, ctx

    try:
        c, ctx = asyncio.run(scenario())
        assert ctx == {"trace_id": c.global_trace_id, "host": "sys-a"}
    finally:
        a.close()


def test_get_trace_context_none_without_tracing():
    assert get_trace_context() is None


def test_host_scoped_spans_and_tree(tmp_path):
    """With host, queries return only that system's subtree — the composite
    PK read side can disambiguate instead of mixing spans."""
    a = Astrolabe(str(tmp_path / "t.db"))
    try:
        with a.trace("ask", host="alpha", trace_id="shared12345678") as ca:
            with span("hop"):
                pass
        with a.trace("ask", host="beta", trace_id="shared12345678") as cb:
            with span("tool.search"):
                pass

        # whole-trace views (no host): everything
        assert len(a.get_trace_spans("shared12345678")) == 4
        # host-scoped: only that system's subtree
        assert [s["operation"] for s in
                a.get_trace_spans("shared12345678", host="alpha")] == \
            ["ask", "hop"]
        assert [s["operation"] for s in
                a.get_trace_spans("shared12345678", host="beta")] == \
            ["ask", "tool.search"]

        ta = a.get_trace("shared12345678", host="alpha")
        tb = a.get_trace("shared12345678", host="beta")
        assert ta["root_span_id"] == ca.root_span_id
        assert tb["root_span_id"] == cb.root_span_id

        tree = a.build_span_tree("shared12345678", host="beta")
        assert tree["trace"]["host"] == "beta"
        assert [c["operation"] for c in tree["tree"]["children"]] == \
            ["tool.search"]
    finally:
        a.close()


def test_two_systems_two_dbs_share_trace_id(tmp_path):
    """Distributed storage: system A generates the id, system B records its
    own spans under the same global id in its own db file."""
    db_a = SQLiteBackend(str(tmp_path / "a.db"))
    db_b = SQLiteBackend(str(tmp_path / "b.db"))
    a = Astrolabe(backend=db_a)
    b = Astrolabe(backend=db_b)
    try:
        with a.trace("ask", host="system-a") as ca:
            with span("hop", hop_number=1):
                pass
        # ...a calls system B over the wire, forwarding the trace id...
        with b.trace("ask", host="system-b", trace_id=ca.global_trace_id) as cb:
            with span("tool.search"):
                pass

        assert ca.global_trace_id == cb.global_trace_id
        assert ca.global_trace_id != ca.root_span_id

        ta = db_a.get_trace(ca.global_trace_id)
        tb = db_b.get_trace(ca.global_trace_id)
        assert ta is not None and ta["host"] == "system-a"
        assert tb is not None and tb["host"] == "system-b"
        # each db only holds its own system's spans
        assert [s["operation"] for s in db_a.get_trace_spans(ca.global_trace_id)] == \
            ["ask", "hop"]
        assert [s["operation"] for s in db_b.get_trace_spans(ca.global_trace_id)] == \
            ["ask", "tool.search"]
    finally:
        a.close()
        b.close()


def test_nested_entry_is_independent_tree(tmp_path):
    """A downstream atrace() nested inside an upstream trace must start its
    own tree (parent=None), never attach to the outer system's stack."""
    a = Astrolabe(str(tmp_path / "a.db"))
    b = Astrolabe(str(tmp_path / "b.db"))
    try:
        async def scenario():
            async with a.atrace("ask", host="outer") as ca:
                async with aspan("hop"):
                    pass
                ctx = get_trace_context()
                # downstream call nested inside the outer trace
                async with b.atrace("ask", host="inner",
                                    trace_id=ctx["trace_id"]) as cb:
                    async with aspan("tool.search"):
                        pass
                return ca, cb

        ca, cb = asyncio.run(scenario())
        assert ca.global_trace_id == cb.global_trace_id

        # outer system: ask + hop, one local root, tree intact
        outer = a.build_span_tree(ca.global_trace_id)
        assert outer["tree"]["operation"] == "ask"
        assert [c["operation"] for c in outer["tree"]["children"]] == ["hop"]

        # inner system: ask + tool.search under its own root, parent=None
        inner = b.build_span_tree(cb.global_trace_id)
        assert inner["tree"]["operation"] == "ask"
        assert inner["tree"]["parent_span_id"] is None
        assert [c["operation"] for c in inner["tree"]["children"]] == \
            ["tool.search"]

        # each db materialized exactly one traces row
        assert a.count_traces() == 1
        assert b.count_traces() == 1
    finally:
        a.close()
        b.close()
